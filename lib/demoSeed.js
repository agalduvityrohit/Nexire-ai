//
// Consumed by lib/server/dataStore.js, which seeds the demo's in-memory store
// from this on first read each time it's empty (a fresh serverless instance
// has no memory of the last one, so this re-seeds automatically rather than
// depending on a one-time script).

function daysAgo(n) {
  return new Date(Date.now() - n * 86400000).toISOString().slice(0, 10);
}

function hoursFromNow(n) {
  return new Date(Date.now() + n * 3600000).toISOString();
}

function stamp(n) {
  const d = new Date(Date.now() - n * 86400000);
  return `${d.toISOString().slice(0, 10)} · ${d.toLocaleTimeString("en-US", { hour: "numeric", minute: "2-digit" })}`;
}

