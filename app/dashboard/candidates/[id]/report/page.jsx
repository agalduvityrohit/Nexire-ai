function BigScore({ value }) {
  const size = 96;
  const stroke = 7;
  const r = (size - stroke) / 2;
  const c = 2 * Math.PI * r;
  const color = value >= 80 ? "var(--color-success)" : value >= 65 ? "var(--color-warn)" : "var(--color-danger)";

  return (
    <div className="flex items-center gap-4">
      <div className="relative" style={{ width: size, height: size }}>
        <svg width={size} height={size} className="-rotate-90">
          <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke="var(--color-line)" strokeWidth={stroke} />
          <motion.circle
            cx={size / 2}
            cy={size / 2}
            r={r}
            fill="none"
            stroke={color}
            strokeWidth={stroke}
            strokeLinecap="round"
            strokeDasharray={c}
            initial={{ strokeDashoffset: c }}
            animate={{ strokeDashoffset: c - (c * value) / 100 }}
            transition={{ duration: 1, ease: [0.22, 1, 0.36, 1], delay: 0.15 }}
          />
        </svg>
        <div className="absolute inset-0 flex flex-col items-center justify-center">
          <span className="text-[26px] font-semibold leading-none tabular-nums tracking-[-0.03em] text-ink">
            {value}
          </span>
          <span className="mt-1 text-[9.5px] uppercase tracking-[0.08em] text-muted">Overall</span>
        </div>
      </div>
    </div>
  );
}

function RadarChart({ dimensions }) {
  const size = 240;
  const cx = size / 2;
  const cy = size / 2;
  const radius = 78;
  const n = dimensions.length;

  const point = (i, ratio) => {
    const angle = (Math.PI * 2 * i) / n - Math.PI / 2;
    return [cx + Math.cos(angle) * radius * ratio, cy + Math.sin(angle) * radius * ratio];
  };

  const polygon = (ratio) =>
    Array.from({ length: n }, (_, i) => point(i, ratio).join(",")).join(" ");

  const dataPoints = dimensions.map((d, i) => point(i, d.score / 100).join(",")).join(" ");

  return (
    <div className="mt-4 flex justify-center">
      <svg viewBox={`0 0 ${size} ${size}`} className="w-full max-w-[260px]" role="img" aria-label="Score profile">
        {[0.25, 0.5, 0.75, 1].map((ratio) => (
          <polygon
            key={ratio}
            points={polygon(ratio)}
            fill="none"
            stroke="var(--color-line)"
            strokeWidth="1"
          />
        ))}
        {dimensions.map((_, i) => {
          const [x, y] = point(i, 1);
          return <line key={i} x1={cx} y1={cy} x2={x} y2={y} stroke="var(--color-line)" strokeWidth="1" />;
        })}

        <motion.polygon
          points={dataPoints}
          fill="var(--color-primary)"
          fillOpacity="0.14"
          stroke="var(--color-primary)"
          strokeWidth="1.8"
          strokeLinejoin="round"
          initial={{ opacity: 0, scale: 0.7 }}
          animate={{ opacity: 1, scale: 1 }}
          style={{ transformOrigin: "center" }}
          transition={{ duration: 0.7, ease: [0.22, 1, 0.36, 1], delay: 0.2 }}
        />

        {dimensions.map((d, i) => {
          const [x, y] = point(i, d.score / 100);
          return <circle key={d.label} cx={x} cy={y} r="3" fill="var(--color-primary)" />;
        })}

        {dimensions.map((d, i) => {
          const [x, y] = point(i, 1.24);
          return (
            <text
              key={d.label}
              x={x}
              y={y}
              textAnchor={x > cx + 4 ? "start" : x < cx - 4 ? "end" : "middle"}
              dominantBaseline="middle"
              fontSize="9.5"
              fill="var(--color-muted)"
              fontWeight="500"
            >
              {d.label}
            </text>
          );
        })}
      </svg>
    </div>
  );
}
